# ---- the oracle: a PNG reader and a pinhole, both independent of the code under test ----

def read_png(path):
    """`(width, height, rows)` of an 8-bit non-interlaced RGB/RGBA PNG; `rows[y][x]` is `(r, g, b)`."""
    data = Path(path).read_bytes()
    assert data[:8] == PNG_SIGNATURE, f'{path} is not a PNG'
    at, idat, header = 8, b'', None
    while at < len(data):
        length, kind = struct.unpack('>I4s', data[at:at + 8])
        chunk = data[at + 8:at + 8 + length]
        if kind == b'IHDR':
            header = struct.unpack('>IIBBBBB', chunk)
        elif kind == b'IDAT':
            idat += chunk
        at += 12 + length
    width, height, depth, color, _, _, interlace = header
    assert depth == 8 and color in (2, 6) and interlace == 0, header
    bpp = 3 if color == 2 else 4
    raw = zlib.decompress(idat)
    stride = width * bpp
    rows, previous = [], bytearray(stride)
    for y in range(height):
        line = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        filter_type = raw[y * (stride + 1)]
        for i in range(stride):
            left = line[i - bpp] if i >= bpp else 0
            up = previous[i]
            corner = previous[i - bpp] if i >= bpp else 0
            if filter_type == 1:
                line[i] = (line[i] + left) & 255
            elif filter_type == 2:
                line[i] = (line[i] + up) & 255
            elif filter_type == 3:
                line[i] = (line[i] + (left + up) // 2) & 255
            elif filter_type == 4:
                guess = left + up - corner
                pa, pb, pc = abs(guess - left), abs(guess - up), abs(guess - corner)
                pick = left if pa <= pb and pa <= pc else up if pb <= pc else corner
                line[i] = (line[i] + pick) & 255
        previous = line
        rows.append([tuple(line[x * bpp:x * bpp + 3]) for x in range(width)])
    return width, height, rows


def project_point(point, width, height):
    """Pixel of a scene-space point from the default scene camera: `[0,1,5]` at the origin, 50 degrees."""
    eye = (0.0, 1.0, 5.0)
    to = (-eye[0], -eye[1], -eye[2])
    norm = math.sqrt(sum(c * c for c in to))
    forward = tuple(c / norm for c in to)
    right = (-forward[2], 0.0, forward[0])
    norm = math.hypot(right[0], right[2])
    right = tuple(c / norm for c in right)
    up = (right[1] * forward[2] - right[2] * forward[1],
          right[2] * forward[0] - right[0] * forward[2],
          right[0] * forward[1] - right[1] * forward[0])
    offset = tuple(point[i] - eye[i] for i in range(3))
    dot = lambda a, b: sum(x * y for x, y in zip(a, b))  # noqa: E731
    depth = dot(offset, forward)
    focal = height / 2 / math.tan(math.radians(25))
    return (round(width / 2 + focal * dot(offset, right) / depth),
            round(height / 2 - focal * dot(offset, up) / depth))


def far_from_background(pixel, by):
    return max(abs(pixel[i] - BACKGROUND[i]) for i in range(3)) > by


def near_background(pixel):
    return max(abs(pixel[i] - BACKGROUND[i]) for i in range(3)) <= 12


def ball_splat(center, radius, count, seed=7):
    """A `.splat` file (32-byte records) of `count` bright splats inside a ball: synthetic data."""
    rng = random.Random(seed)
    out = bytearray()
    while len(out) < count * 32:
        offset = [rng.uniform(-1, 1) for _ in range(3)]
        if sum(v * v for v in offset) > 1:
            continue
        for axis in range(3):
            out += struct.pack('<f', center[axis] + offset[axis] * radius)
        out += struct.pack('<fff', radius * 0.05, radius * 0.05, radius * 0.05)
        out += bytes([230, 180, 90, 255]) + bytes([255, 128, 128, 128])
    return bytes(out)


def write_variants(fixtures, count=VARIANTS):
    """`count` scene files that differ by a thousandth (so each is its own thumbnail), and `far.splat`."""
    base = json.loads((fixtures / 'scene.tessel-scene.json').read_text())
    paths = []
    for index in range(count):
        scene = json.loads(json.dumps(base))
        scene['objects'][0]['position'][0] = round(-2.2 + 0.001 * (index + 1), 6)
        path = fixtures / f'variant-{index:02d}.tessel-scene.json'
        path.write_text(json.dumps(scene, indent=2))
        paths.append(path)
    (fixtures / 'far.splat').write_bytes(ball_splat((1000.0, -200.0, 300.0), 5.0, 3000))
    # Same number of splats as `cloud.splat` (a relink needs comparable streams), other bytes and place.
    (fixtures / 'moved.splat').write_bytes(ball_splat((900.0, 150.0, -250.0), 4.0, 4000, seed=11))
    return paths


def check_pictures(check, label, scene_png, splat_png, far_png):
    """The pixel oracle on the PNG files of one project."""
    for name, png in (('scene', scene_png), ('splat', splat_png), ('far splat', far_png)):
        width, height, _ = read_png(png)
        check(f'{label}: the {name} thumbnail is {WIDTH}x{HEIGHT}', (width, height) == (WIDTH, HEIGHT), (width, height))
    width, height, scene = read_png(scene_png)
    _, _, splat = read_png(splat_png)
    _, _, far = read_png(far_png)
    box = project_point((-2.2, 0.0, 0.0), width, height)
    sphere = project_point((2.2, 0.0, 0.0), width, height)
    middle = project_point((0.0, 0.0, 0.0), width, height)
    center = (width // 2, height // 2)
    at = lambda rows, p: rows[p[1]][p[0]]  # noqa: E731
    b, s = at(scene, box), at(scene, sphere)
    check(f'{label}: the scene thumbnail is orange where the box projects {box}', b[0] > b[2] + 60, b)
    check(f'{label}: the scene thumbnail is blue where the sphere projects {sphere}', s[2] > s[0] + 60, s)
    check(f'{label}: the scene thumbnail shows the cloud at {middle}',
          far_from_background(at(scene, middle), 40), at(scene, middle))
    check(f'{label}: the splat thumbnail is framed from its file: the cloud is at the middle {center}',
          far_from_background(at(splat, center), 40), at(splat, center))
    check(f'{label}: the far splat (1000 units from the origin) is also at the middle {center}',
          far_from_background(at(far, center), 40), at(far, center))
    corners = [(2, 2), (width - 3, height - 3)]
    check(f'{label}: the corners of all three are the background',
          all(near_background(at(rows, c)) for rows in (scene, splat, far) for c in corners))
    check(f'{label}: the bare splat is not the scene\'s picture',
          Path(splat_png).read_bytes() != Path(scene_png).read_bytes())


# ---- observation of a job that is really running ----

def in_flight(info):
    """A thumbnail job that is running with some frames drawn and some still to go."""
    done, total = info.get('done') or 0, info.get('total') or 0
    return info.get('state') == 'running' and 1 <= done < total


def is_final(info):
    return info.get('state') in ('succeeded', 'failed', 'cancelled')


def await_in_flight(read_jobs, what, seconds=300, sleep=time.sleep, clock=time.time):
    """The first thumbnail job seen in flight. A job that ended without ever being seen is a FAIL."""
    deadline = clock() + seconds
    seen = []
    while clock() < deadline:
        jobs = [job for job in read_jobs() if job.get('kind') == 'thumbnail']
        seen = jobs
        for job in jobs:
            if in_flight(job):
                return job
        if jobs and all(is_final(job) for job in jobs):
            raise ProofFailure(f'{what}: every thumbnail job ended before one was seen running with frames left '
                               f'({[(j.get("state"), j.get("done"), j.get("total")) for j in jobs]})')
        sleep(0.15)
    raise ProofFailure(f'{what}: no thumbnail job was seen running within {seconds}s ({seen})')


def require_cancelled_midway(check, label, info):
    """The job ended `cancelled` and not all frames were drawn: it was stopped, not finished."""
    state, done, total = info.get('state'), info.get('done') or 0, info.get('total') or 0
    check(f'{label}: the job ended cancelled (not {state!r})', state == 'cancelled', info)
    check(f'{label}: it was cancelled midway ({done} of {total} frames drawn)', 0 < total and done < total, info)


def capture(surface, check, path, what):
    """The OS capture of the editor's window. A refusal is a SKIP, never a pass."""
    shot, reason = surface.capture(path)
    if not shot:
        check.skip(f'{what}: the OS capture of the window', reason)
        return None
    data = Path(shot).read_bytes()
    check(f'{what}: the OS capture is a PNG of the window', data[:8] == PNG_SIGNATURE and len(data) > 2000, len(data))
    return shot


# ---- the scenario ----

def make_scenario(fixtures, variants):
    def scenario(surface, check, scratch):
        shots = []

        def ok(request):
            good, payload = surface.op(request)
            if not good:
                raise ProofFailure(f'{request} -> {payload}')
            return payload

        def wait_for(predicate, what, seconds=240):
            deadline = time.time() + seconds
            last = None
            while time.time() < deadline:
                last = predicate()
                if last:
                    return last
                time.sleep(0.4)
            raise ProofFailure(f'timed out waiting for {what}: {last}')

        def thumbnail_jobs():
            if surface.name == 'native':
                good, payload = surface.get('jobs')
                if not good:
                    raise ProofFailure(f'get jobs -> {payload}')
                return payload['state']['all']
            return ok({'op': 'job.list'})['jobs']

        def create(name, sequence, workspace):
            return ok({'op': 'project.create', 'name': name, 'sequence': sequence, 'rate': 24, 'width': FRAME[0],
                       'height': FRAME[1], 'length': 48, 'dir': str(workspace)})

        def import_media(paths):
            ok({'op': 'media.import', 'paths': [str(p) for p in paths]})
            if surface.name == 'native':
                wait_for(lambda: len(ok({'op': 'status'})['assets']) == len(paths), 'the import')

        def library():
            """`{id: asset}` with each asset's thumbnail report, from `media.status` (the same op on both)."""
            return {a['id']: a for a in ok({'op': 'media.status'})['assets']}

        def header_matches(project, sequence, step):
            label = f'{project} / {sequence}'
            h = ok({'op': 'project.header'})
            check(f'{step}: project.header says {label!r}',
                  h['label'] == label and h['project'] == project and h['sequence'] == sequence, h)
            status = ok({'op': 'status'})
            check(f'{step}: status.header is the same answer', status['header'] == h, status['header'])
            if surface.name == 'native':
                good, node = surface.get('node:13')
                check(f'{step}: the semantic title node (node:13) is {label!r}', good and node['label'] == label, node)
            return h

        def pictures(workspace, everything=False):
            got = library()
            wanted = list(got) if everything else [SPLAT_ID, SCENE_ID, FAR_ID]
            reports = {k: got[k]['thumbnail'] for k in wanted}
            check(f'{len(wanted)} thumbnails are ready',
                  all(r['state'] == 'ready' for r in reports.values()),
                  {k: r['state'] for k, r in reports.items() if r['state'] != 'ready'})
            for id_, report in reports.items():
                check(f'{id_}: the picture is inside this project\'s workspace cache',
                      report['path'].startswith(str(workspace)) and '/.tessel/cache/' in report['path'], report['path'])
                check(f'{id_}: the picture file exists and is {report["width"]}x{report["height"]}',
                      Path(report['path']).is_file() and (report['width'], report['height']) == (WIDTH, HEIGHT), report)
            return reports[SCENE_ID]['path'], reports[SPLAT_ID]['path'], reports[FAR_ID]['path'], reports

        def job_ended(job_id):
            """The thumbnail job `job_id` once it is final, else `None`."""
            found = {j['id']: j for j in thumbnail_jobs() if j.get('kind') == 'thumbnail'}.get(job_id)
            return found if found and is_final(found) else None

        def draw():
            """Headless asks for the pictures (no scheduler there); the window draws them by itself."""
            return ok({'op': 'media.thumbnails'}) if surface.name == 'headless' else None

        def thumbnail_of(asset):
            return library()[asset]['thumbnail']

        def settled():
            now = library()
            jobs = [j for j in thumbnail_jobs() if j.get('kind') == 'thumbnail']
            return all(is_final(j) for j in jobs) and all(a['thumbnail']['state'] == 'ready' for a in now.values())

        ws_a, ws_b = scratch / 'ws-a', scratch / 'ws-b'
        # A document's workspace is its own folder: each project is saved inside its workspace.
        doc_a, doc_b = ws_a / 'a.tessel.json', ws_b / 'b.tessel.json'
        base_files = [fixtures / 'cloud.splat', fixtures / 'scene.tessel-scene.json', fixtures / 'far.splat']

        # ---- the header follows the project, and the first pictures ----
        created = create('Aurora', 'cut-a', ws_a)
        check('project A is created in its own workspace', created['workspace'] == str(ws_a), created)
        header_matches('Aurora', 'cut-a', 'after project.create')
        import_media(base_files)
        edits_before = ok({'op': 'status'})['persistence'], ok({'op': 'history.status'})
        before = library()
        check('the imported splats and scene are in the library', set(before) == {SPLAT_ID, SCENE_ID, FAR_ID},
              set(before))
        if surface.name == 'headless':
            check('before the job all pictures are pending',
                  all(a['thumbnail']['state'] == 'pending' for a in before.values()), before)
            report = ok({'op': 'media.thumbnails'})
            check('media.thumbnails draws all three (two splats and a scene)',
                  report['ready'] == 3 and report['applied']['failed'] == [], report)
        else:
            wait_for(lambda: all(a['thumbnail']['state'] == 'ready' for a in library().values()),
                     'the window\'s own thumbnail jobs')
        scene_a, splat_a, far_a, _ = pictures(ws_a)
        check_pictures(check, 'project A', scene_a, splat_a, far_a)
        edits_after = ok({'op': 'status'})['persistence'], ok({'op': 'history.status'})
        check('drawing the pictures is not an edit (revision, dirty flag and undo history unchanged)',
              edits_before == edits_after, (edits_before, edits_after))
        ok({'op': 'project.save', 'path': str(doc_a)})

        # ---- a second project with the same asset IDs and files, and twenty more scenes ----
        create('Basalt', 'cut-b', ws_b)
        header_matches('Basalt', 'cut-b', 'after a second project.create')
        if surface.name == 'native':
            import_media(base_files + variants)
            # B's window job is drawing now: wait until it is REALLY running, with frames left, then replace B.
            job = await_in_flight(thumbnail_jobs, 'B\'s window job')
            check(f'B\'s thumbnail job is running ({job["done"]} of {job["total"]} frames drawn)',
                  in_flight(job), job)
            # The user stops the automatic job: it ends cancelled midway and the window does not start it again.
            ok({'op': 'job.cancel', 'job': job['id']})
            stopped = wait_for(lambda: job_ended(job['id']), 'the job the user cancelled to end')
            require_cancelled_midway(check, 'B\'s job, cancelled by the user', stopped)
            ids_at_cancel = {j['id'] for j in thumbnail_jobs() if j.get('kind') == 'thumbnail'}
            time.sleep(PAUSE_SECONDS)
            ids_later = {j['id'] for j in thumbnail_jobs() if j.get('kind') == 'thumbnail'}
            check(f'the user\'s pause holds: no thumbnail job started in the {PAUSE_SECONDS}s after the cancel',
                  ids_later == ids_at_cancel and job['id'] in ids_at_cancel, (ids_at_cancel, ids_later))
            check('nothing of the cancelled job was applied (every picture of B is still pending)',
                  all(a['thumbnail']['state'] == 'pending' for a in library().values()), library())
            # An explicit request resumes it.
            ok({'op': 'media.thumbnails'})
            job = await_in_flight(thumbnail_jobs, 'B\'s resumed job')
            check(f'media.thumbnails resumed it ({job["done"]} of {job["total"]} frames drawn)', in_flight(job), job)
            # The same document opened again is another session: the resumed job must stop, and the new session
            # (not paused) draws by itself.
            ok({'op': 'project.save', 'path': str(doc_b)})
            ok({'op': 'project.open', 'path': str(doc_b)})
            header_matches('Basalt', 'cut-b', 'after project.open of the same document B again')
            replaced = wait_for(lambda: job_ended(job['id']), 'the resumed job to end')
            require_cancelled_midway(check, 'B\'s resumed job, replaced by the same document opened again', replaced)
            job = await_in_flight(thumbnail_jobs, 'the new session of B\'s own job')
            check('the new session of the same document draws by itself (the old pause belonged to the old session)',
                  in_flight(job), job)
            ok({'op': 'project.save', 'path': str(doc_b)})
            ok({'op': 'project.open', 'path': str(doc_a)})
            header_matches('Aurora', 'cut-a', 'after project.open of A (B\'s job was running)')
            samples = []

            def settled_sampling():
                now = library()
                samples.append({k: v['thumbnail'].get('path') for k, v in now.items()})
                return settled()

            wait_for(settled_sampling, 'every thumbnail job to end with A\'s pictures ready')
            old = {j['id']: j for j in thumbnail_jobs()}[job['id']]
            require_cancelled_midway(check, 'B\'s job, replaced by A', old)
            scene_again, splat_again, far_again, _ = pictures(ws_a)
            check('A shows its own pictures (the same files as before), never B\'s',
                  (scene_again, splat_again, far_again) == (scene_a, splat_a, far_a), (scene_again, splat_again))
            check('no sample taken while the jobs ran held a path outside A\'s workspace',
                  all(p is None or p.startswith(str(ws_a)) for s in samples for p in s.values()), samples[-3:])
            ok({'op': 'project.open', 'path': str(doc_b)})
            header_matches('Basalt', 'cut-b', 'after project.open of B')
            wait_for(lambda: all(a['thumbnail']['state'] == 'ready' for a in library().values()),
                     'B\'s own thumbnail jobs')
            scene_b, splat_b, far_b, reports_b = pictures(ws_b, everything=True)
            check(f'B has all {len(variants) + 3} thumbnails', len(reports_b) == len(variants) + 3, len(reports_b))
        else:
            import_media(base_files + variants)
            check('B starts with a pending picture for every asset (a new project, an empty book)',
                  len(library()) == len(variants) + 3 and
                  all(a['thumbnail']['state'] == 'pending' for a in library().values()), library())
            ok({'op': 'project.save', 'path': str(doc_b)})
            queued = ok({'op': 'media.thumbnails', 'wait': False})
            first = queued['job']
            running = await_in_flight(lambda: [ok({'op': 'job.get', 'job': first})], 'B\'s first job')
            check(f'B\'s first job is running ({running["done"]} of {running["total"]} frames drawn)',
                  in_flight(running), running)
            ok({'op': 'job.cancel', 'job': first})
            ended = ok({'op': 'job.wait', 'job': first})
            require_cancelled_midway(check, 'B\'s first job', ended)
            good, refused = surface.op({'op': 'job.commit', 'job': first})
            check('the cancelled job\'s result cannot be applied', not good, refused)
            check('nothing of the cancelled job reached the library (every picture still pending)',
                  all(a['thumbnail']['state'] == 'pending' for a in library().values()), library())
            # A job that finishes for B, then the SAME document is opened again: another session, so it is refused.
            third = ok({'op': 'media.thumbnails', 'wait': False})['job']
            ok({'op': 'job.wait', 'job': third})
            ok({'op': 'project.open', 'path': str(doc_b)})
            header_matches('Basalt', 'cut-b', 'after project.open of the same document B again')
            reopened = ok({'op': 'job.commit', 'job': third})
            check('a result drawn for the first opening of B is refused by its reopening (same document, new session)',
                  reopened['applied'].get('stale') is True, reopened)
            check('nothing of it reached the library (every picture of the reopened B is pending)',
                  all(a['thumbnail']['state'] == 'pending' for a in library().values()), library())
            # A new job for the same project, finished but not applied; then A is opened under it.
            second = ok({'op': 'media.thumbnails', 'wait': False})['job']
            ok({'op': 'job.wait', 'job': second})
            ok({'op': 'project.open', 'path': str(doc_a)})
            header_matches('Aurora', 'cut-a', 'after project.open of A')
            committed = ok({'op': 'job.commit', 'job': second})
            check('B\'s finished result is refused when A is open (stale, nothing applied)',
                  committed['applied'].get('stale') is True, committed)
            a_now = library()
            check('A did not receive any picture of B',
                  all(a['thumbnail']['state'] == 'pending' for a in a_now.values()), a_now)
            report = ok({'op': 'media.thumbnails'})
            check('A\'s pictures come back from its cache', report['ready'] == 3, report)
            scene_again, splat_again, far_again, _ = pictures(ws_a)
            check('the cache serves the very same files',
                  (scene_again, splat_again, far_again) == (scene_a, splat_a, far_a),
                  (scene_again, splat_again))
            ok({'op': 'project.open', 'path': str(doc_b)})
            header_matches('Basalt', 'cut-b', 'after project.open of B')
            report = ok({'op': 'media.thumbnails'})
            check('B\'s new job draws every picture (what the cancelled one drew comes from the cache)',
                  report['ready'] == len(variants) + 3, report)
            scene_b, splat_b, far_b, reports_b = pictures(ws_b, everything=True)
            check(f'B has all {len(variants) + 3} thumbnails', len(reports_b) == len(variants) + 3, len(reports_b))
        check('B\'s pictures are not A\'s files',
              scene_b != scene_a and splat_b != splat_a and far_b != far_a, (scene_b, scene_a))
        check_pictures(check, 'project B', scene_b, splat_b, far_b)

        # ---- a dependency changes: the splat a scene is drawn with is relinked to other content ----
        # (A scene whose splat is missing cannot be imported at all: `media.import` refuses it with
        # `missing_dependency`, so "missing -> present" has no live path; the library test covers it.)
        create('Chalk', 'cut-c', scratch / 'ws-c')
        header_matches('Chalk', 'cut-c', 'after a third project.create')
        import_media([fixtures / 'cloud.splat', fixtures / 'scene.tessel-scene.json'])
        draw()
        wait_for(lambda: all(a['thumbnail']['state'] == 'ready' for a in library().values()),
                 'the splat and the scene to be drawn')
        scene_c, splat_c = thumbnail_of(SCENE_ID), thumbnail_of(SPLAT_ID)
        check('the scene is drawn with its splat',
              scene_c['state'] == 'ready' and Path(scene_c['path']).is_file(), scene_c)
        width, height, rows = read_png(scene_c['path'])
        box = project_point((-2.2, 0.0, 0.0), width, height)
        check('the scene thumbnail is orange where the box projects',
              rows[box[1]][box[0]][0] > rows[box[1]][box[0]][2] + 60, rows[box[1]][box[0]])
        middle = project_point((0.0, 0.0, 0.0), width, height)
        check('and shows its cloud at the middle',
              far_from_background(rows[middle[1]][middle[0]], 40), rows[middle[1]][middle[0]])
        # Relink the splat to other content: its own picture and the scene's (drawn with it) are made again.
        ok({'op': 'media.relink', 'asset': SPLAT_ID, 'path': str(fixtures / 'moved.splat'), 'accept_changed': True})
        draw()

        def redrawn():
            now = library()
            return (now[SPLAT_ID]['thumbnail']['state'] == 'ready' and now[SCENE_ID]['thumbnail']['state'] == 'ready'
                    and now[SPLAT_ID]['thumbnail'].get('identity') != splat_c.get('identity')
                    and now[SCENE_ID]['thumbnail'].get('identity') != scene_c.get('identity'))

        wait_for(redrawn, 'the relinked splat and the scene drawn with it to be made again')
        scene_r, splat_r = thumbnail_of(SCENE_ID), thumbnail_of(SPLAT_ID)
        check('the scene\'s identity follows its splat: a new picture, the old file is kept but not shown',
              scene_r['path'] != scene_c['path'] and Path(scene_c['path']).is_file(), (scene_c['path'], scene_r['path']))
        check('the relinked splat has its own new picture',
              splat_r['path'] != splat_c['path'], (splat_c['path'], splat_r['path']))
        _, _, relinked = read_png(splat_r['path'])
        check('the relinked splat (900 units from the origin) is framed from its new file: it is at the middle',
              far_from_background(relinked[HEIGHT // 2][WIDTH // 2], 40), relinked[HEIGHT // 2][WIDTH // 2])
        _, _, redrawn_scene = read_png(scene_r['path'])
        sphere = project_point((2.2, 0.0, 0.0), width, height)
        check('the scene still shows its box and sphere after the relink',
              redrawn_scene[box[1]][box[0]][0] > redrawn_scene[box[1]][box[0]][2] + 60
              and redrawn_scene[sphere[1]][sphere[0]][2] > redrawn_scene[sphere[1]][sphere[0]][0] + 60,
              (redrawn_scene[box[1]][box[0]], redrawn_scene[sphere[1]][sphere[0]]))

        # ---- an error leaves the project intact ----
        before_status = ok({'op': 'status'})
        undo_before = ok({'op': 'history.status'})
        good, error = surface.op({'op': 'media.thumbnails', 'assets': ['ghost']})
        check('an unknown asset is refused with unknown_element', not good and error['code'] == 'unknown_element', error)
        after_status = ok({'op': 'status'})
        check('the project is untouched by the refusal (revision, undo depth, header)',
              after_status['persistence'] == before_status['persistence']
              and after_status['header'] == before_status['header'], (before_status['persistence'],
                                                                       after_status['persistence']))
        check('the undo history is untouched by the refusal', ok({'op': 'history.status'}) == undo_before, undo_before)

        # ---- native: the monitor draws a real frame of a clip (the earlier captures had no clip) ----
        if surface.name == 'native':
            ok({'op': 'track.add', 'id': 'mon-track', 'name': 'Monitor', 'kind': 'video'})
            ok({'op': 'clip.add', 'id': 'mon-clip', 'track': 'mon-track', 'asset': SCENE_ID, 'start': 0,
                'duration': 24})
            good, payload = surface.set('timeline.playhead', 'frame', 0)
            check('the playhead is on the first frame of the clip', good, payload)

            def monitor():
                good, payload = surface.get('monitor.viewport')
                state = payload.get('state') if good and isinstance(payload, dict) else None
                last = (state or {}).get('last_frame') or {}
                return state if state and state.get('phase') == 'ready' and last.get('hash') else None

            state = wait_for(monitor, 'the monitor to draw a frame of the clip', 120)
            last = state['last_frame']
            check(f'the monitor drew a real frame of the clip (hash {str(last["hash"])[:12]})',
                  state.get('phase') == 'ready' and bool(last.get('hash')), state)
            mean = last.get('mean')
            if isinstance(mean, list) and len(mean) >= 3:
                check('that frame is not the empty background', far_from_background(tuple(mean[:3]), 6), mean)
            shot = capture(surface, check, scratch / 'bl144-window.png', 'the window with a clip on the monitor')
            if shot:
                shots.append(shot)
        return shots
    return scenario


def run_all(surfaces, scenario, out):
    """Runs the scenario on every `(class, binary)`; one surface failing never stops the next."""
    report = {}
    for cls, binary in surfaces:
        result = run_surface(cls, binary, scenario, out, home_prefix='b4-')
        report[cls.name] = result
        print(f'{cls.name}: {result["passed"]} passed, {result["skipped"]} skipped, '
              f'{"FAILED" if result["failed"] else "ok"}', flush=True)
    return report


def exit_code(report):
    if any(result['failed'] for result in report.values()):
        return 1
    return 0 if all(result['complete'] for result in report.values()) else 2


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--editor', default=str(ROOT / 'target/debug/tessel-editor'))
    parser.add_argument('--render', default=str(ROOT / 'target/debug/tessel-render'))
    parser.add_argument('--out')
    parser.add_argument('--report')
    parser.add_argument('--only', choices=['headless', 'native'])
    parser.add_argument('--copy-screenshots', help='copy the captures here (nothing is written to docs/ by default)')
    args = parser.parse_args()
    free = free_gib()
    if free < MIN_FREE_GIB:
        sys.exit(f'only {free:.1f} GiB free; the floor is {MIN_FREE_GIB} GiB')
    # A short temporary directory: the socket path under a long one does not fit a Unix socket.
    tempfile.tempdir = '/tmp'
    out = Path(args.out or tempfile.mkdtemp(prefix='bl144-proof-')).resolve()
    out.mkdir(parents=True, exist_ok=True)
    fixtures = out / 'fixtures'
    try:
        subprocess.run([str(ROOT / 'scripts/fixtures'), str(fixtures)], check=True, capture_output=True, timeout=300)
        variants = write_variants(fixtures)
    except (subprocess.SubprocessError, OSError) as error:
        sys.exit(f'cannot write the fixtures: {error}')
    surfaces = [(Headless, args.render), (Native, args.editor)]
    surfaces = [s for s in surfaces if not args.only or s[0].name == args.only]
    report = run_all(surfaces, make_scenario(fixtures, variants), out)
    if args.copy_screenshots:
        target = Path(args.copy_screenshots)
        target.mkdir(parents=True, exist_ok=True)
        for result in report.values():
            for shot in result.get('screenshot') or []:
                shutil.copy(shot, target / Path(shot).name)
    if args.report:
        Path(args.report).write_text(json.dumps(report, indent=2))
    sys.exit(exit_code(report))


if __name__ == '__main__':
    main()
