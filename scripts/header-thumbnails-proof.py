#!/usr/bin/env python3
"""BL144 — the header follows the open project and the library draws real splat/scene thumbnails,
proved on two separate surfaces with the same scenario.

    python3 scripts/directed-scene-proof/with-gpu-lock.py \
        python3 scripts/header-thumbnails-proof.py [--editor target/debug/tessel-editor] \
        [--render target/debug/tessel-render] [--out DIR] [--report FILE] [--only headless|native] \
        [--copy-screenshots DIR]

* headless (no window): `tessel-render`, JSON Lines over stdio, the real Node + Chrome renderer. A window's
  socket is not headless evidence.
* native window: the DIRECT editor binary with its own short `HOME` (own socket, settings, recents: the
  user's window and project are never touched), driven only by its `ui` CLI (`op`, `get`, `set`, `invoke`). No
  pointer, no coordinates. The window schedules the thumbnail jobs itself; the script only reads the tree.

Transport, process cleanup and the OS capture are `scripts/proof_surface.py` (shared with the other BL140-BL144
proofs; its logic is not edited here). Every surface runs inside `run_surface`: a binary that is missing, exits,
hangs or answers garbage is a failure recorded for THAT surface, the other surface still runs and the report is
still written.

The files are synthetic: the standard fixtures `./scripts/fixtures` writes (a splat cloud and a scene with an
orange box, a blue sphere and that cloud) plus, written here, a dense ball of splats far from the origin (`far`)
and twenty scene variants (a box moved by a thousandth) that only exist to keep the thumbnail job busy long
enough to be observed running. Nothing is generated by a model and no private media is used.

Oracle, computed here with a plain pinhole and independently of the Rust and JS code under test:
  * scene: from the default scene camera (`[0,1,5]` looking at the origin, 50 degrees) the thumbnail must be
    orange at the projected box centre, blue at the projected sphere centre, background in the corners;
  * bare splat: it is framed from its own file, so the cloud (the standard one and `far`, 1000 units from the
    origin) must be at the middle of the picture, the corners the background, and the picture must not be the
    scene's.

Proved on both: `project.header` and `status.header` name `Project / Sequence` after create, open and a second
open; a thumbnail job draws one PNG per splat and scene at the sequence aspect and size; the pixels match the
oracle; a picture is never applied to another project (the same asset IDs and files are in both, on purpose); a
job that is REALLY running (observed `running` with some frames drawn and not all) is cancelled/replaced and
ends `cancelled` before drawing everything, its result is not applied and the new job's pictures are right; an
unknown asset is refused and the project is untouched; the SAME document opened again (another session) refuses the
result drawn for the first opening (headless: `job.commit` is `stale`; native: the running job ends cancelled and the
new session draws by itself); relinking the splat a scene is drawn with gives the splat and the scene new identities,
new pictures and the right pixels. Native only: a job the USER cancels (seen running first) is not started again by
the window's tick (the pause holds) until an explicit `media.thumbnails` resumes it; the semantic `node:13` label
equals the header, the tree's `thumbnail` state per `media:<id>`, and a monitor that drew a real frame of a clip.

A precondition that does not hold (the job finished before it could be cancelled, the monitor never drew) is a
FAIL, never a pass. A missing OS capture is a recorded SKIP (the run is then `complete: false`, exit 2).
Screenshots are written under `--out`; they are copied elsewhere only with `--copy-screenshots`.

Not proven here: a physical pointer, a real GPU (SwiftShader), a real SHARP file (BL143, another PR), a
black-monitor root cause (BL144.4: the earlier captures were of a sequence with no clip), a dependency going from
missing to present (a scene whose splat is not in the library is refused by `media.import` with
`missing_dependency`, so no operation reaches that state; `crates/media/tests/thumbnails.rs` covers it with the
library edited directly), the user's pause surviving a video export (BL144.10), an export racing a thumbnail.
"""
