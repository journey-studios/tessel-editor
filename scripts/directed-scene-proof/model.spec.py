#!/usr/bin/env python3
"""The reference model must agree with the ORIGIN oracle before it may judge the destination.

    python3 scripts/directed-scene-proof/model.spec.py

Compares `model.py` with `docs/migration/fixtures/expected` (generated by the origin's real
functions) on every probed frame of the supported valid fixtures, with the oracle tolerance
`1e-9 + 1e-12·|x|` (camera, node locals) and `1e-10 + 1e-12·|x|` (world matrices).
"""
import importlib.util
import json
import pathlib
import sys
import unittest

HERE = pathlib.Path(__file__).resolve().parent
FIXTURES = HERE.parent.parent / "docs/migration/fixtures"
spec = importlib.util.spec_from_file_location("model", HERE / "model.py")
model = importlib.util.module_from_spec(spec)
spec.loader.exec_module(model)


def close(actual, expected, absolute, relative):
    return abs(actual - expected) <= absolute + relative * abs(expected)


def load(case):
    bundle = json.loads((FIXTURES / f"bundles/{case}.bundle.json").read_text())
    expected = json.loads((FIXTURES / f"expected/{case}.expected.json").read_text())
    return bundle, expected


class AgainstTheOrigin(unittest.TestCase):
    def frames(self, case):
        bundle, expected = load(case)
        ok = [f for f in expected["evaluation"]["editFrames"] if f["ok"]]
        self.assertGreater(len(ok), 5)
        return bundle, ok

    def test_camera_recipes_and_easings(self):
        # dollyIn(easeInOutCubic) + hold + truckRight(easeOutCubic), every probed frame.
        bundle, frames = self.frames("valid-minimal-continuous")
        for entry in frames:
            got = model.frame_state(bundle, entry["editFrame"])["camera"]
            want = entry["state"]["camera"]
            for key in ("position", "target"):
                for axis in "xyz":
                    self.assertTrue(
                        close(got[key]["xyz".index(axis)], want[key][axis], 1e-9, 1e-12),
                        (entry["editFrame"], key, axis, got[key], want[key]),
                    )
            self.assertTrue(close(got["fovDeg"], want["fovDeg"], 1e-9, 1e-12))

    def test_node_channels_hierarchy_and_sockets(self):
        # cycle + event + static, Euler composition, Y-rotated parents and a socket.
        bundle, frames = self.frames("valid-graph-sockets-performance")
        seen_motion = False
        for entry in frames:
            state = model.frame_state(bundle, entry["editFrame"])
            for node_id, want in entry["worldMatrices"].items():
                got = state["worldMatrices"][node_id]
                for index in range(16):
                    self.assertTrue(
                        close(got[index], want[index], 1e-10, 1e-12),
                        (entry["editFrame"], node_id, index, got[index], want[index]),
                    )
            if entry["state"]["performanceOverrides"]:
                seen_motion = True
        self.assertTrue(seen_motion)

    def test_paint_order_follows_render_order_then_document_order(self):
        bundle, _ = load("valid-minimal-continuous")
        self.assertEqual(model.paint_order(bundle["sceneDefinitions"][0]), ["backdrop", "figure"])

    def test_unsupported_input_is_refused_not_guessed(self):
        with self.assertRaises(model.Unsupported):
            model.ease("bounce", 0.5)
        with self.assertRaises(model.Unsupported):
            model.clip_camera({"initialPosition": {"x": 0, "y": 0, "z": 1}, "initialTarget": {"x": 0, "y": 0, "z": 0},
                               "initialFovDeg": 40, "segments": [{"recipe": "orbit", "durationFrames": 4, "from": "initial"}]}, 0)


if __name__ == "__main__":
    unittest.main(verbosity=2)
