#!/usr/bin/env python3
"""Corpus and independent expectations for the directed-scene EXPORT proof (BL019/BL008, front R10).

    python3 scripts/directed-scene-export-proof/export_corpus.py                 # (re)writes ./corpus
    python3 scripts/directed-scene-export-proof/export_corpus.py --check         # fails on any difference/stray file
    python3 scripts/directed-scene-export-proof/export_corpus.py --materialize DIR  # also writes the 33 MB 4K detail PNG, hash-checked

WHY a corpus of its own (and not only `scripts/directed-scene-proof/corpus`): an export has needs the
frame proof does not: a rational (NTSC) frame rate, a frame range that crosses the shot cut and the
event boundaries, an original PNG as large as the 4K output (so a proxy would show), and an audio mix
reference (so "no directed audio promised" can be tested). Nothing here is read back from the
destination: pixel expectations come from `scripts/directed-scene-proof/model.py` (independent maths,
validated against the origin oracle by `model.spec.py`), timing expectations are exact fractions
derived from the bundle's own `fps`.

Provenance: the three small PNGs are drawn by the P generator (`corpus.py`, flat colours and a
barcode); the 4K detail PNG and the audio mix are drawn here, from scratch. `private_media` is false.
The detail PNG is NOT committed (33 MB): it is regenerated byte-for-byte (stored deflate blocks, so the
bytes do not depend on a zlib build) and checked against the SHA-256 in `corpus/provenance.json`.
"""
