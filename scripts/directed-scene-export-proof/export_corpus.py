# ---------------------------------------------------------------------------------- PNG / WAV writers
def png_from_rows(width, height, row_bytes):
    """RGBA8 PNG from `row_bytes[y]` (width*4 bytes each); stored deflate: bytes independent of zlib."""
    raw = b"".join(b"\x00" + row_bytes[y] for y in range(height))
    header = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    return (b"\x89PNG\r\n\x1a\n" + p_corpus._chunk(b"IHDR", header)
            + p_corpus._chunk(b"IDAT", p_corpus._stored_zlib(raw)) + p_corpus._chunk(b"IEND", b""))


def _row(width, painter):
    return b"".join(bytes(painter(x)) + b"\xff" for x in range(width))


# Detail texture layout (pixels). Every band is full width; blocks sit below the stripes.
DETAIL_BANDS = {
    "stripes1": (200, 400), "stripes2": (600, 800), "stripes4": (1000, 1200), "colors": (1400, 2000),
}
DETAIL_COLORS = [(220, 30, 30), (30, 190, 50), (40, 60, 230), (30, 200, 210),
                 (210, 40, 200), (230, 210, 40), (240, 130, 20), (130, 50, 170)]
BLOCK_W, BLOCK_X0 = 400, 200
MARKER = 64  # red square top-left, blue bottom-right: a flip, crop or offset moves them


def detail_rows():
    gray = (128, 128, 128)
    cache = {}

    def build(kind, y):
        # Rows of one band are identical except inside the two marker strips, so those are the cache key.
        key = (kind, y < MARKER, y >= DETAIL_H - MARKER)

        def painter(x):
            if y < MARKER and x < MARKER:
                return (255, 0, 0)
            if y >= DETAIL_H - MARKER and x >= DETAIL_W - MARKER:
                return (0, 0, 255)
            if kind == "stripes1":
                return (255, 255, 255) if x % 2 == 0 else (0, 0, 0)
            if kind == "stripes2":
                return (255, 255, 255) if (x // 2) % 2 == 0 else (0, 0, 0)
            if kind == "stripes4":
                return (255, 255, 255) if (x // 4) % 2 == 0 else (0, 0, 0)
            if kind == "colors":
                index = (x - BLOCK_X0) // BLOCK_W
                return DETAIL_COLORS[index] if 0 <= index < len(DETAIL_COLORS) and BLOCK_X0 <= x else gray
            return gray

        if key not in cache:
            cache[key] = _row(DETAIL_W, painter)
        return cache[key]

    rows = []
    for y in range(DETAIL_H):
        kind = "gray"
        for name, (lo, hi) in DETAIL_BANDS.items():
            if lo <= y < hi:
                kind = name
        rows.append(build(kind, y))
    return rows


def detail_png():
    return png_from_rows(DETAIL_W, DETAIL_H, detail_rows())


def audio_mix():
    """Mono 16-bit mix, 440 Hz then 880 Hz. Returns (wav bytes, sha256 of the whole WAV file).

    The bundle's `sourcePcmHashSha256` is, despite its name, the hash of the entire WAV file header included
    (docs/migration/source-feature-inventory.md, "Limitações"); the resource gate rejects anything else with
    `hash_mismatch`, which is how the first version of this corpus (PCM payload hash) was caught."""
    import io
    samples = bytearray()
    half = AUDIO_RATE * AUDIO_SECONDS // 2
    for index in range(AUDIO_RATE * AUDIO_SECONDS):
        hz = AUDIO_HZ[0] if index < half else AUDIO_HZ[1]
        value = int(round(0.5 * 32767 * math.sin(2 * math.pi * hz * index / AUDIO_RATE)))
        samples += struct.pack("<h", value)
    buffer = io.BytesIO()
    with wave.open(buffer, "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(AUDIO_RATE)
        handle.writeframes(bytes(samples))
    wav = buffer.getvalue()
    return wav, hashlib.sha256(wav).hexdigest()


def sha256(data):
    return hashlib.sha256(data).hexdigest()


# ---------------------------------------------------------------------------------- bundles
def _records():
    records, images = [], {}
    for entry in p_corpus.ASSETS:
        record, data = p_corpus.asset_record(entry)
        records.append(record)
        images[record["relativePath"]] = data
    return records, images


def _profile(bundle, width, height, fps):
    bundle["renderProfile"].update({"width": width, "height": height, "fps": dict(fps),
                                    "browserChannel": "synthetic-export-proof-r10"})
    bundle["fps"] = dict(fps)


def main_bundle(records):
    bundle = copy.deepcopy(p_corpus.build_bundle(records))
    bundle["bundleId"], bundle["revisionId"] = "r10-main", "rev-1"
    _profile(bundle, 1920, 1080, {"numerator": 24, "denominator": 1})
    # WHY stronger motion than the frame-proof corpus: an export is judged frame by frame, and a frame can only be
    # told from its neighbours (a duplicate, a skip, a swap) if the picture changes enough between them. The P
    # corpus moves the hero ~1.5 px per frame in the hold segments; here it sways 50 degrees over 36 frames and
    # the stage slides 2.2 units in 16 frames. The model supports exactly these channel kinds.
    for channel in bundle["performanceTracks"][0]["channels"]:
        if channel["channelId"] == "stage-slide":
            channel["durationFrames"], channel["delta"] = 16, p_corpus.v3(2.2, 0, 0)
        elif channel["channelId"] == "hero-sway":
            channel["periodFrames"], channel["amplitude"] = 36, 50
    return bundle


def ntsc_bundle(records):
    bundle = main_bundle(records)
    bundle["bundleId"] = "r10-ntsc"
    _profile(bundle, 1920, 1080, {"numerator": 30000, "denominator": 1001})
    return bundle


def audio_bundle(records, mix_hash):
    bundle = main_bundle(records)
    bundle["bundleId"] = "r10-audio"
    bundle["audio"] = {"mixRelativePath": "audio/mix.wav", "editStartSeconds": 0,
                       "editEndSecondsExclusive": float(AUDIO_SECONDS), "sourcePcmHashSha256": mix_hash}
    return bundle


def detail_bundle(detail_record):
    """One plane that fills the whole 16:9 frame exactly: a camera at z=6 with a 40 degree vertical FOV sees
    2*6*tan(20deg) units of height. At 3840x2160 every output pixel then samples one texel (1:1)."""
    height_units = 2 * 6 * math.tan(math.radians(20))
    width_units = height_units * 16 / 9
    ref = {key: detail_record[key] for key in ("assetId", "revisionId", "contentHash", "relativePath")}
    node = p_corpus.node
    nodes = [
        node("root", None, "group", p_corpus.v3(0, 0, 0)),
        node("detail", "root", "imagePlane", p_corpus.v3(0, 0, 0), assetRef=ref, widthSceneUnits=width_units,
             heightSceneUnits=height_units, renderOrder=0),
    ]
    fps = {"numerator": 24, "denominator": 1}
    frames = 12
    return {
        "schemaVersion": "1.0", "bundleId": "r10-detail", "revisionId": "rev-1", "fps": fps,
        "editDurationFrames": frames,
        "renderProfile": {"width": DETAIL_W, "height": DETAIL_H, "fps": dict(fps), "colorSpace": "srgb-display",
                          "alphaMode": "straight", "premultiplyOnUpload": False, "videoCodec": "h264-yuv420p",
                          "threeRevision": "0.187.0", "browserChannel": "synthetic-export-proof-r10"},
        "assets": [detail_record], "performanceTracks": [], "compositionPasses": [],
        "sceneDefinitions": [{"id": "scene-d", "schemaVersion": "1.0", "rootNodeId": "root", "nodes": nodes}],
        "sceneInstances": [{"id": "inst-d", "sceneDefinitionId": "scene-d", "durationFrames": frames,
                            "performanceTrackIds": []}],
        "cameraClips": [{"id": "cam-d", "initialPosition": p_corpus.v3(0, 0, 6), "initialTarget": p_corpus.v3(0, 0, 0),
                         "initialFovDeg": 40, "segments": [{"recipe": "hold", "durationFrames": frames, "from": "initial"}]}],
        "shots": [{"id": "shot-d", "sceneInstanceId": "inst-d", "editRange": {"startFrame": 0, "endFrameExclusive": frames},
                   "instanceStartFrame": 0, "cameraClipId": "cam-d", "cameraInFrame": 0, "intent": "detail 1:1"}],
    }


# ---------------------------------------------------------------------------------- expectations
def textures():
    return {entry[0]: p_corpus.decoded(entry[4]) for entry in p_corpus.ASSETS}


NEIGHBORS = [(dx, dy) for dx in (-MARGIN, 0, MARGIN) for dy in (-MARGIN, 0, MARGIN) if (dx, dy) != (0, 0)]


def frame_probes(bundle, frame, tex):
    """Flat-interior pixels of the reference frame, a few per visible layer. Independent of the output size:
    `refX/refY` are reference-grid pixels, the harness maps them by `floor((ref + .5) / REF * output)`."""
    state = model.frame_state(bundle, frame)
    found = {}
    for py in range(MARGIN + 3, REF_H - MARGIN - 3, GRID_STEP):
        for px in range(MARGIN + 3, REF_W - MARGIN - 3, GRID_STEP):
            here = model.visible_layer(state, REF_W, REF_H, px, py, tex)
            if here is None:
                continue
            if any(model.visible_layer(state, REF_W, REF_H, px + dx, py + dy, tex) != here for dx, dy in NEIGHBORS):
                continue
            found.setdefault(here["layer"], []).append(
                {"refX": px, "refY": py, "layer": here["layer"], "color": here["color"]})
    chosen = []
    for layer in sorted(found):
        candidates = found[layer]
        step = max(1, len(candidates) // PROBES_PER_LAYER)
        chosen.extend(candidates[::step][:PROBES_PER_LAYER])
    return chosen


def probes_at(bundle, frame, positions, tex):
    """The model's answer at fixed reference positions (used for cross-frame identity, same positions)."""
    state = model.frame_state(bundle, frame)
    out = []
    for px, py in positions:
        here = model.visible_layer(state, REF_W, REF_H, px, py, tex)
        out.append(None if here is None else here["color"])
    return out


def edited_bundle(bundle):
    out = copy.deepcopy(bundle)
    hero = next(n for n in out["sceneDefinitions"][0]["nodes"] if n["id"] == "hero")
    hero["localPosition"] = dict(SNAPSHOT_EDIT["hero_value"])
    out["cameraClips"][0]["initialFovDeg"] = SNAPSHOT_EDIT["fov_value"]
    return out


def fps_fraction(bundle):
    return Fraction(bundle["fps"]["numerator"], bundle["fps"]["denominator"])


def frac(value):
    return f"{value.numerator}/{value.denominator}"


def case_expectation(case, bundles):
    fps = fps_fraction(bundles[case["bundle"]])
    return {"bundle": case["bundle"], "preset": case["preset"], "from": case["frm"], "frames": case["frames"],
            "fps": frac(fps), "durationSeconds": frac(Fraction(case["frames"]) / fps),
            "output": [1920, 1080] if case["preset"] == "fullhd" else [3840, 2160],
            "budgetSeconds": case["budgetSeconds"], "covers": case["covers"], "kind": case.get("kind", "scene")}


def geometry_of(bundle):
    """What the picture depends on. `main`, `ntsc` and `audio` differ in fps/audio only, so one set of
    per-frame probes serves all three (asserted, not assumed)."""
    out = copy.deepcopy(bundle)
    for key in ("bundleId", "fps", "audio", "renderProfile"):
        out.pop(key, None)
    return out


def scene_frames():
    """Scene frames any scene case or the snapshot case exports."""
    frames = set()
    for case in CASES.values():
        if case.get("kind", "scene") == "scene":
            frames.update(range(case["frm"], case["frm"] + case["frames"]))
    return sorted(frames)


def detail_expectation():
    return {
        "texture": {"width": DETAIL_W, "height": DETAIL_H, "assetId": "detail"},
        "bands": {name: {"y0": lo, "y1": hi} for name, (lo, hi) in DETAIL_BANDS.items()},
        "colorBlocks": [{"x0": BLOCK_X0 + i * BLOCK_W, "x1": BLOCK_X0 + (i + 1) * BLOCK_W, "color": list(c)}
                        for i, c in enumerate(DETAIL_COLORS)],
        "markers": {"topLeft": {"size": MARKER, "color": [255, 0, 0]},
                    "bottomRight": {"size": MARKER, "color": [0, 0, 255]}},
        "mapping": "output pixel (x, y) = texel (x, y): plane fills the frame exactly (camera z=6, fov 40, 16:9)",
    }


def snapshot_expectation(bundle, geometry, tex):
    edited = edited_bundle(bundle)
    case = CASES["snapshot_1080"]
    frames = range(case["frm"], case["frm"] + case["frames"])
    return {
        "edit": SNAPSHOT_EDIT,
        # The edited scene at the SAME reference positions as the unedited probes: the contrast that proves
        # the edit would show in the file if the export did not hold a snapshot.
        "editedAtSamePositions": {
            str(f): probes_at(edited, f, [(p["refX"], p["refY"]) for p in geometry[str(f)]], tex) for f in frames},
    }


def build_all():
    """{relative path: bytes} of the committed corpus, plus the detail PNG bytes held aside."""
    records, images = _records()
    mix, mix_hash = audio_mix()
    detail_bytes = detail_png()
    detail_record = {"assetId": "detail", "revisionId": "rev-1", "contentHash": sha256(detail_bytes),
                     "relativePath": "assets/detail.png", "widthPx": DETAIL_W, "heightPx": DETAIL_H,
                     "alphaMode": "opaque", "colorSpace": "srgb"}
    bundles = {"main": main_bundle(records), "ntsc": ntsc_bundle(records), "audio": audio_bundle(records, mix_hash),
               "detail": detail_bundle(detail_record)}
    files = dict(images)
    files["audio/mix.wav"] = mix
    for name, bundle in bundles.items():
        files[f"bundle.{name}.json"] = (json.dumps(bundle, indent=2) + "\n").encode()
    tex = textures()
    base = geometry_of(bundles["main"])
    assert geometry_of(bundles["ntsc"]) == base and geometry_of(bundles["audio"]) == base
    geometry = {str(f): frame_probes(bundles["main"], f, tex) for f in scene_frames()}
    expected = {
        "corpusVersion": CORPUS_VERSION,
        "note": "Generated by export_corpus.py from the independent model (scripts/directed-scene-proof/model.py) and "
                "exact fractions of the bundles' own fps. No destination output is stored here.",
        "reference": {"width": REF_W, "height": REF_H, "margin": MARGIN},
        "bundles": {name: {"file": f"bundle.{name}.json", "bundleId": b["bundleId"], "fps": frac(fps_fraction(b)),
                           "editFrames": b["editDurationFrames"], "sha256": sha256(files[f"bundle.{name}.json"])}
                    for name, b in bundles.items()},
        "assets": {r["assetId"]: {"file": r["relativePath"], "sha256": r["contentHash"], "widthPx": r["widthPx"],
                                  "heightPx": r["heightPx"]} for r in records + [detail_record]},
        "audioMix": {"file": "audio/mix.wav", "sha256": sha256(mix), "sourcePcmHashSha256": mix_hash, "hz": list(AUDIO_HZ),
                     "seconds": AUDIO_SECONDS, "sampleRate": AUDIO_RATE},
        "tolerances": TOLERANCES,
        "geometry": {"bundles": ["main", "ntsc", "audio"], "frameProbes": geometry},
        "cases": {cid: case_expectation(case, bundles) for cid, case in CASES.items()},
        "cancelCase": {**CANCEL_CASE, "fps": "24/1"},
        "rangeErrors": RANGE_ERRORS,
        "snapshot": snapshot_expectation(bundles["main"], geometry, tex),
        "detail": detail_expectation(),
        "audioPolicy": {
            "statement": "A directed scene has no audio unless its bundle names a mix. A bundle WITHOUT `audio` must export "
                         "with zero audio streams and without claiming audio. A bundle WITH `audio` must either carry that "
                         "mix (audio stream whose spectrum holds the tone at the right window) or be refused with a typed "
                         "error and no file. Silently dropping it, or adding an audio stream with other content, fails.",
            "toneHz": list(AUDIO_HZ), "mixWindowSeconds": [0, AUDIO_SECONDS],
            "explicitLimit": "a successful export with no audio stream is accepted only if its result carries a warning whose "
                             "code is listed in adapters.json `audio_not_mixed_warning_codes` (an explicit, typed limit)"},
    }
    files["expected.json"] = (json.dumps(expected, indent=2) + "\n").encode()
    committed = {name: {"sha256": sha256(data), "bytes": len(data)} for name, data in files.items()}
    provenance = {
        "corpusVersion": CORPUS_VERSION,
        "generator": {"file": "scripts/directed-scene-export-proof/export_corpus.py",
                      "sha256": sha256((HERE / "export_corpus.py").read_bytes()),
                      "model": {"file": "scripts/directed-scene-proof/model.py", "sha256": sha256((P_DIR / "model.py").read_bytes())},
                      "pGenerator": {"file": "scripts/directed-scene-proof/corpus.py", "sha256": sha256((P_DIR / "corpus.py").read_bytes())},
                      "python": ">=3.10"},
        "origin": "none: drawn from scratch; pixel expectations from model.py validated against the origin oracle",
        "private_media": False,
        "files": dict(sorted(committed.items())),
        "notCommitted": {"assets/detail.png": {"sha256": sha256(detail_bytes), "bytes": len(detail_bytes),
                                               "why": "33 MB; regenerated deterministically by --materialize"}},
    }
    files["provenance.json"] = (json.dumps(provenance, indent=2) + "\n").encode()
    return files, detail_bytes


def write(target):
    target = pathlib.Path(target)
    files, _ = build_all()
    if target.exists():
        shutil.rmtree(target)
    for name, data in files.items():
        path = target / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)


def materialize(target):
    """Copies the committed corpus to `target` and adds the generated 4K PNG, verifying its hash."""
    target = pathlib.Path(target)
    shutil.copytree(CORPUS_DIR, target, dirs_exist_ok=True)
    data = detail_png()
    wanted = json.loads((CORPUS_DIR / "provenance.json").read_text())["notCommitted"]["assets/detail.png"]["sha256"]
    if sha256(data) != wanted:
        raise SystemExit(f"detail.png differs from provenance.json ({sha256(data)} != {wanted})")
    (target / "assets/detail.png").write_bytes(data)
    return target


def check(target):
    target = pathlib.Path(target)
    files, _ = build_all()
    problems = []
    for name, data in files.items():
        path = target / name
        if not path.is_file():
            problems.append(f"missing {name}")
        elif path.read_bytes() != data:
            problems.append(f"differs {name}")
    if target.exists():
        for path in target.rglob("*"):
            if path.is_file() and str(path.relative_to(target)) not in files:
                problems.append(f"unexpected {path.relative_to(target)}")
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default=str(CORPUS_DIR))
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--materialize", metavar="DIR")
    args = parser.parse_args()
    if args.materialize:
        print(f"materialized {materialize(args.materialize)}")
        return 0
    if args.check:
        problems = check(args.out)
        for problem in problems:
            print("FAIL " + problem)
        print("corpus is up to date" if not problems else f"{len(problems)} problem(s)")
        return 1 if problems else 0
    write(args.out)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
