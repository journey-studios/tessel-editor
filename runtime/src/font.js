const UNKNOWN = '11111 10001 10001 10001 10001 10001 11111';

export const GLYPH_COLUMNS = 5;
export const GLYPH_ROWS = 7;
const ADVANCE = GLYPH_COLUMNS + 1;

const glyphFor = (character) => ROWS[character] ?? ROWS[character.toUpperCase()] ?? UNKNOWN;

/** Size in glyph cells (one blank column between glyphs). */
export const measureText = (text) => ({
  columns: Math.max(1, text.length * ADVANCE - 1),
  rows: GLYPH_ROWS,
});

/**
 * Calls `fillCell(column, row)` for every lit cell of `text`; the caller decides what a cell
 * is (a canvas rectangle in the runtime, a counter in tests).
 */
export const forEachLitCell = (text, fillCell) => {
  [...text].forEach((character, position) => {
    glyphFor(character)
      .split(' ')
      .forEach((bits, row) => {
        for (let column = 0; column < GLYPH_COLUMNS; column += 1) {
          if (bits[column] === '1') fillCell(position * ADVANCE + column, row);
        }
      });
  });
};
