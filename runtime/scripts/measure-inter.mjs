// Measures the advance width of every character a title can hold in the bundled Inter at the
// weight the runtime draws with, and writes `crates/core/src/inter_widths.rs`.
//
// WHY: a text box that wraps (`TextSpec::width`, F070) is broken into lines by the core, not by
// the runtime, so the breaks, the number of lines of a "reveal by line" and the time it takes
// are the same in the plan, the monitor and the export. The core has no font engine; it reads
// this table (thousandths of an em, no kerning: kerning only ever tightens a line, so a line the
// core fits never overflows the box once drawn).
//
//   node scripts/measure-inter.mjs        (from runtime/; needs Chrome, see TESSEL_CHROME)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import puppeteer from 'puppeteer-core';

import { findChrome } from '../worker/chrome.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const output = join(root, '../crates/core/src/inter_widths.rs');
const coverage = readFileSync(join(root, '../crates/core/src/text_coverage.txt'), 'utf8').trim();
// The weight and the family of `src/typographic-text.js`; keep them in step.
const WEIGHT = 860;

const characters = [
  ...Array.from({ length: 0x7e - 0x20 + 1 }, (_, index) => String.fromCharCode(0x20 + index)),
  ...[...coverage],
];

const browser = await puppeteer.launch({ executablePath: findChrome(), headless: true });
try {
  const page = await browser.newPage();
  const bytes = readFileSync(join(root, 'src/fonts/InterVariable.woff2')).toString('base64');
  const widths = await page.evaluate(async (base64, list, weight) => {
    const binary = Uint8Array.from(atob(base64), (char) => char.charCodeAt(0));
    const face = await new FontFace('Tessel Inter', binary.buffer, { weight: '100 900' }).load();
    document.fonts.add(face);
    const context = document.createElement('canvas').getContext('2d');
    context.font = `${weight} 1000px "Tessel Inter"`;
    return list.map((character) => Math.round(context.measureText(character).width));
  }, bytes, characters, WEIGHT);

  const rows = characters.map((character, index) => {
    const escaped = character === '\\' || character === "'" ? `\\${character}` : character;
    return `    ('${escaped}', ${widths[index]}),`;
  });
  writeFileSync(
    output,
    [
      '// Generated by `node runtime/scripts/measure-inter.mjs`; do not edit by hand.',
      `// Advance widths of the bundled Inter at weight ${WEIGHT}, in thousandths of an em.`,
      '',
      '/// `(character, advance)` for printable ASCII, then `text_coverage.txt`, in that order.',
      'pub(crate) const INTER_ADVANCES: &[(char, u16)] = &[',
      ...rows,
      '];',
      '',
    ].join('\n'),
  );
  console.log(`${characters.length} characters -> ${output}`);
} finally {
  await browser.close();
}
